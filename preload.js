const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  lang: ipcRenderer.sendSync('app:lang'), // 'en' or 'sv', fixed until the window reloads
  detectSources: () => ipcRenderer.invoke('sources:detect'),
  detectExportOnly: () => ipcRenderer.invoke('sources:exportOnly'),
  importSources: (sources) => ipcRenderer.invoke('import:sources', sources),
  importHtml: () => ipcRenderer.invoke('import:html'),
  list: () => ipcRenderer.invoke('library:list'),
  update: (id, patch) => ipcRenderer.invoke('bookmark:update', id, patch),
  remove: (ids) => ipcRenderer.invoke('bookmark:remove', ids),
  open: (url) => ipcRenderer.invoke('open:url', url),
  markOpened: (id) => ipcRenderer.invoke('bookmark:opened', id),
  appInfo: () => ipcRenderer.invoke('app:info'),
  logError: (where, message) => ipcRenderer.invoke('app:logError', where, message),
  libraryBackups: () => ipcRenderer.invoke('library:backups'),
  openLibraryBackups: () => ipcRenderer.invoke('library:openBackups'),
  restoreLibraryBackup: (name) => ipcRenderer.invoke('library:restoreBackup', name),
  exportLibrary: () => ipcRenderer.invoke('library:exportJson'),
  importLibrary: () => ipcRenderer.invoke('library:importJson'),
  bulkUpdate: (ids, patch) => ipcRenderer.invoke('bookmark:bulk', ids, patch),
  setFields: (list) => ipcRenderer.invoke('bookmark:setFields', list),
  mergeDuplicates: (keepId, otherIds) => ipcRenderer.invoke('dups:merge', keepId, otherIds),
  mergeAllDuplicates: () => ipcRenderer.invoke('dups:mergeAll'),
  unmergeDuplicates: (tokens) => ipcRenderer.invoke('dups:unmerge', tokens),
  dismissDuplicates: (signature, undo) => ipcRenderer.invoke('dups:dismiss', signature, undo),
  listDeleted: () => ipcRenderer.invoke('deleted:list'),
  restore: (ids) => ipcRenderer.invoke('deleted:restore', ids),
  browserSyncPlan: () => ipcRenderer.invoke('browsers:plan'),
  browserSyncApply: (labels) => ipcRenderer.invoke('browsers:apply', labels),
  browserBackups: () => ipcRenderer.invoke('browsers:backups'),
  browserRestore: (label, file) => ipcRenderer.invoke('browsers:restore', label, file),
  revealFile: (file) => ipcRenderer.invoke('browsers:reveal', file),
  keyStatus: () => ipcRenderer.invoke('key:status'),
  saveKey: (key) => ipcRenderer.invoke('key:save', key),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  ollamaStatus: (model) => ipcRenderer.invoke('ollama:status', model),
  categorize: (ids) => ipcRenderer.invoke('claude:categorize', { ids }),
  bridgeInfo: () => ipcRenderer.invoke('bridge:info'),
  bridgeNewToken: () => ipcRenderer.invoke('bridge:newToken'),
  bridgeOpenFolder: () => ipcRenderer.invoke('bridge:openFolder'),
  bridgeFirefox: () => ipcRenderer.invoke('bridge:firefox'),
  bridgeOpenFirefoxFolder: () => ipcRenderer.invoke('bridge:openFirefoxFolder'),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  onBridgeReport: (fn) => ipcRenderer.on('bridge-report', (_e, r) => fn(r)),
  onAutoImport: (fn) => ipcRenderer.on('auto-import', (_e, r) => fn(r)),
  onFocusSearch: (fn) => ipcRenderer.on('focus-search', () => fn()),
  onAutoLinks: (fn) => ipcRenderer.on('auto-links', (_e, r) => fn(r)),
  onBridgePage: (fn) => ipcRenderer.on('bridge-page', (_e, r) => fn(r)),
  onShowView: (fn) => ipcRenderer.on('show-view', (_e, v) => fn(v)),
  cancelJob: (kind) => ipcRenderer.invoke('job:cancel', kind),
  checkLinks: (ids) => ipcRenderer.invoke('links:check', { ids }),
  exportHtml: (ids, groupBy) => ipcRenderer.invoke('export:html', { ids, groupBy }),
  onProgress: (fn) => ipcRenderer.on('progress', (_e, p) => fn(p)),
});
